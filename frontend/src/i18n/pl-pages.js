/** Polish counts: 1 miesiąc, 2-4 miesiące, 5+ miesięcy (12-14 like 5). */
const plural = (count, one, few, many) => {
  if (count === 1) return one;
  const tens = count % 100;
  return count % 10 >= 2 && count % 10 <= 4 && (tens < 12 || tens > 14) ? few : many;
};

